from exceptionos.ai.guardrails import normalize_ai_response

def test_8_error_response_is_normalized():
    raw = {
        "error": "Insufficient data to answer the question."
    }

    result = normalize_ai_response(raw)

    assert result["answer"]
    assert result["verified_facts"] == []
    assert result["recommendations"]
    assert result["confidence"] == 0.0
    assert result["sources"] == []
    assert result["response_mode"] == "insufficient_data"
